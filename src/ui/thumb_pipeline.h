#ifndef THUMB_PIPELINE_H
#define THUMB_PIPELINE_H

#include <stdbool.h>

#include "file_mgr.h"

/* 缩略图默认尺寸（16:9，与卡片显示尺寸一致，避免二次缩放） */
#define THUMB_PIPELINE_W 160
#define THUMB_PIPELINE_H 90

/* 缩略图输出目录（内存文件系统，重启自动清理与录像列表同步） */
#define THUMB_PIPELINE_DIR "/tmp/thumbs"

/* 队列容量（请求与完成各自独立计数） */
#define THUMB_QUEUE_MAX 16

/* 生成完成项（UI 线程消费） */
typedef struct {
    char video_path[FILE_PATH_MAX]; /* 源录像路径 */
    char bmp_path[FILE_PATH_MAX];   /* 生成的 BMP 路径 */
    bool ok;                        /* 生成是否成功 */
} thumb_done_t;

/*****************************************************************************
 * 函数名称：thumb_pipeline_init
 * 功能描述：创建缩略图目录并启动后台生成线程
 * 返回值：  成功0，失败-1
 * 注意事项：UI 线程调用一次；生成线程 nice 降级避免与录像编码抢 CPU
 *****************************************************************************/
int thumb_pipeline_init(void);

/*****************************************************************************
 * 函数名称：thumb_pipeline_request
 * 功能描述：请求生成指定录像文件的缩略图（异步，线程安全）
 * 输入参数：@video_path - 录像文件完整路径
 * 返回值：  入队成功0，队列满或参数无效-1
 * 注意事项：同文件重复请求由队列去重（已在队列则忽略）
 *****************************************************************************/
int thumb_pipeline_request(const char* video_path);

/*****************************************************************************
 * 函数名称：thumb_pipeline_pop_done
 * 功能描述：取出一个完成项（非阻塞，线程安全）
 * 输出参数：@out - 完成项输出
 * 返回值：  有完成项返回 true，队列空返回 false
 *****************************************************************************/
bool thumb_pipeline_pop_done(thumb_done_t* out);

/*****************************************************************************
 * 函数名称：thumb_pipeline_stop
 * 功能描述：停止生成线程并释放队列（UI 线程退出时调用）
 *****************************************************************************/
void thumb_pipeline_stop(void);

#endif /* THUMB_PIPELINE_H */
