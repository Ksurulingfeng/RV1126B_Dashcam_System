#ifndef RTSP_SERVER_H
#define RTSP_SERVER_H

#include <gst/gst.h>

/*****************************************************************************
 * 函数名称：rtsp_server_init
 * 功能描述：启动 RTSP 服务器（独立线程跑 GLib 主循环）
 * 返回值：  成功返回0，失败返回-1
 * 注意事项：默认端口 8554，挂载点 /stream；
 *           需在 gst_encoder 管线初始化之后调用
 *****************************************************************************/
int rtsp_server_init(void);

/*****************************************************************************
 * 函数名称：rtsp_server_push
 * 功能描述：把一帧编码流 buffer 推给当前 RTSP 客户端（无客户端时丢弃）
 * 输入参数：@buf  - 编码流 buffer（引用计数 +1）
 *           @caps - 编码流 caps（格式变化时更新 appsrc）
 * 注意事项：可在任意线程调用；内部加锁，跨管线桥接 appsrc
 *****************************************************************************/
void rtsp_server_push(GstBuffer *buf, GstCaps *caps);

/*****************************************************************************
 * 函数名称：rtsp_server_deinit
 * 功能描述：停止 RTSP 服务器线程并释放资源
 *****************************************************************************/
void rtsp_server_deinit(void);

#endif /* RTSP_SERVER_H */
