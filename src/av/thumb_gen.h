#ifndef THUMB_GEN_H
#define THUMB_GEN_H

/*****************************************************************************
 * 函数名称：thumb_gen_from_video
 * 功能描述：解码视频文件的第一个视频帧，缩放后保存为 BMP 缩略图
 * 输入参数：@src_path - 源视频路径（如 rec_00001.mp4）
 *           @bmp_path - 缩略图输出路径（如 rec_00001.bmp）
 *           @width    - 缩略图宽度（像素）
 *           @height   - 缩略图高度（像素）
 * 返回值：  成功返回0，失败返回负数
 * 注意事项：1. 只解码第一帧，缩略图场景无需解码全程
 *           2. 输出格式为 24 位 BMP（BGR 排列）
 *           3. 该函数可被多线程调用（每个线程使用独立上下文）
 *****************************************************************************/
int thumb_gen_from_video(const char *src_path, const char *bmp_path,
                         int width, int height);

#endif /* THUMB_GEN_H */
